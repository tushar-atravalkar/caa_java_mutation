"""
Engine-side narrowing to a diff's changed lines (Java / Python / Go).

None of pitest, mutmut or gremlins accepts a line range, so each is narrowed
as far as its own switches allow; run.py's `_filter_to_diff_scope` still
filters the RESULT by exact line afterwards, so narrowing here is purely a
speed optimisation and can never change a score:

    Java    pitest   -DexcludedMethods  -> only methods overlapping the diff
    Python  mutmut   v2 pre_mutation hook -> exact lines
                     v3 mutant-name globs   -> only functions overlapping the diff
    Go      gremlins --exclude-files    -> only the changed files of a package

Every helper fails open: when it cannot tell what to exclude it returns
nothing to exclude, so the engine mutates more, never less.
"""

import ast
import json
import os
import re
from pathlib import Path

_JAVA_NOT_METHODS = {
    "if", "for", "while", "switch", "catch", "synchronized", "return", "new",
    "else", "do", "try", "throw", "assert", "super", "this", "case",
}


def _blank_comments_and_literals(src: str) -> str:
    """Replace comment/string/char contents with spaces, keeping newlines, so
    brace matching and line numbers survive."""
    out, i, n = [], 0, len(src)
    while i < n:
        c, nxt = src[i], src[i + 1] if i + 1 < n else ""
        if c == "/" and nxt == "/":
            while i < n and src[i] != "\n":
                out.append(" "); i += 1
        elif c == "/" and nxt == "*":
            while i < n and not (src[i] == "*" and i + 1 < n and src[i + 1] == "/"):
                out.append("\n" if src[i] == "\n" else " "); i += 1
            out.append("  "); i += 2
        elif src.startswith('"""', i):
            end = src.find('"""', i + 3)
            end = n if end < 0 else end + 3
            out.append("".join("\n" if ch == "\n" else " " for ch in src[i:end])); i = end
        elif c in "\"'":
            out.append(c); i += 1
            while i < n and src[i] != c and src[i] != "\n":
                out.append(" "); i += 2 if src[i] == "\\" else 1
            out.append(c); i += 1
        else:
            out.append(c); i += 1
    return "".join(out)


_METHOD_HEAD = re.compile(r"(\w+)\s*\([^;{}]*\)\s*(?:throws\s+[\w.,\s]+)?\{")


def java_method_spans(source: str) -> list:
    """[(name, start_line, end_line)] for every method body in `source`
    (1-based, inclusive). Constructors and initialisers are not returned."""
    clean = _blank_comments_and_literals(source)
    spans = []
    for m in _METHOD_HEAD.finditer(clean):
        name = m.group(1)
        if name in _JAVA_NOT_METHODS:
            continue
        # a method declaration has a return type before its name; a call or a
        # constructor does not. Require an identifier/`>`/`]` token before it.
        before = clean[:m.start(1)].rstrip()
        if not before or not re.search(r"[\w>\]]$", before):
            continue
        prev_word = re.search(r"(\w+)$", before)
        if prev_word and prev_word.group(1) in {"new", "return", "else", "throw"}:
            continue
        depth, i = 0, m.end() - 1
        while i < len(clean):
            depth += (clean[i] == "{") - (clean[i] == "}")
            if depth == 0:
                break
            i += 1
        spans.append((name,
                      clean.count("\n", 0, m.start(1)) + 1,
                      clean.count("\n", 0, i) + 1))
    return spans


def java_excluded_methods(lines_by_file: dict) -> list:
    """Method names pitest may skip, given {source_file: changed_lines}: names
    with no body touching a changed line in ANY target file. pitest matches on
    the bare name across all target classes, so a name touched anywhere (or by
    an overload) stays in. A file with no line set is not narrowed at all, so
    its method names are never excluded."""
    defined, touched = set(), set()
    for source_file, changed in lines_by_file.items():
        try:
            spans = java_method_spans(Path(source_file).read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError):
            return []
        names = {n for n, _, _ in spans}
        if not changed:
            touched |= names
            continue
        defined |= names
        touched |= {n for n, a, b in spans if any(a <= l <= b for l in changed)}
    return sorted(defined - touched)


def mutmut_v2_config(lines_by_file: dict) -> str:
    """Source of a `mutmut_config.py` whose pre_mutation hook skips every
    mutation on a line outside `lines_by_file` ({posix path: [lines]})."""
    return (
        "# generated by the mutation workflow (diff narrowing) -- safe to delete\n"
        "import json, os\n"
        f"_LINES = json.loads({json.dumps(json.dumps(lines_by_file))})\n"
        "def pre_mutation(context):\n"
        "    fn = context.filename.replace(os.sep, '/')\n"
        "    for path, lines in _LINES.items():\n"
        "        if fn == path or fn.endswith('/' + path) or path.endswith('/' + fn):\n"
        "            if (context.current_line_index + 1) not in lines:\n"
        "                context.skip = True\n"
        "            return\n"
    )


def mutmut_v3_name_filters(lines_by_file: dict) -> list:
    """fnmatch globs for `mutmut run <globs>` (v3), given {source_file: changed_lines}.

    v3 names mutants `<module>.x_<func>__mutmut_<n>` and, for methods,
    `<module>.xǁ<Class>ǁ<method>__mutmut_<n>`. The module part is derived from
    mutmut's own source root, so it is wildcarded rather than guessed: a glob
    that over-matches only runs extra mutants, and the diff-scope filter on the
    results keeps the score exact. Returns [] (= run everything) whenever any
    file cannot be narrowed, because the globs apply to the whole run."""
    globs = set()
    for source_file, changed in lines_by_file.items():
        if not changed:
            return []
        try:
            tree = ast.parse(Path(source_file).read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, SyntaxError):
            return []

        def visit(body, klass=None):
            for node in body:
                if isinstance(node, ast.ClassDef):
                    # a nested class is keyed by its own name only
                    visit(node.body, node.name)
                elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    first = min([node.lineno] + [d.lineno for d in node.decorator_list])
                    if any(first <= l <= node.end_lineno for l in changed):
                        key = f"xǁ{klass}ǁ{node.name}" if klass else f"x_{node.name}"
                        globs.add(f"*{key}__mutmut_*")

        visit(tree.body)
    return sorted(globs)


def go_excluded_files(project_root: str, targets, only_files) -> list:
    """`--exclude-files` regexes for the .go files that share a target package
    directory but are not in `only_files` (the changed sources). Test files are
    left to gremlins, which already ignores them."""
    keep = {os.path.normcase(os.path.abspath(f)) for f in only_files}
    regexes = []
    for tid in targets:
        rel = tid.removeprefix("./")
        d = Path(project_root, "." if rel == "..." else rel.removesuffix("/..."))
        if not d.is_dir():
            continue
        for f in d.glob("*.go"):
            if f.name.endswith("_test.go") or os.path.normcase(str(f.resolve())) in keep:
                continue
            regexes.append(r"(^|/)" + re.escape(f.relative_to(project_root).as_posix()) + "$")
    return regexes
